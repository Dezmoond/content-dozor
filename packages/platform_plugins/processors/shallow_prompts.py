# -*- coding: utf-8 -*-
"""Промпты и константы поверхностного 4-классового анализа (Qwen validation)."""
from __future__ import annotations

from typing import Dict

# Ключи классов в JSON модели
CLASS_EXTREMIST = "extremist"
CLASS_DANGEROUS = "dangerous"
CLASS_PROVOCATIVE = "provocative"
CLASS_NEGATIVE = "negative"

CLASS_LABELS_RU: Dict[str, str] = {
    CLASS_EXTREMIST: "Экстремистский (по закону РФ)",
    CLASS_DANGEROUS: "Опасный / призыв к плохим действиям",
    CLASS_PROVOCATIVE: "Провокационный",
    CLASS_NEGATIVE: "Вызывающий негативную реакцию",
}

VALID_CLASSES = set(CLASS_LABELS_RU.keys())

SYSTEM_PROMPT = (
    "Ты классификатор фраз в русском тексте. "
    "Найди только те фрагменты, которые попадают в один из 4 классов. "
    "Классы (поле class — только латиницей):\n"
    "1) extremist — экстремистский контент по смыслу законодательства РФ "
    "(разжигание ненависти/вражды по признакам, призывы к экстремистской деятельности, "
    "оправдание терроризма/экстремизма и т.п.).\n"
    "2) dangerous — опасный текст или прямой/косвенный призыв к вреду, насилию, "
    "преступлению, самовреду, порче имущества и иным плохим действиям "
    "(если это не экстремизм по п.1).\n"
    "3) provocative — провокационный текст: намеренно разжигает конфликт, "
    "оскорбляет группы/лиц, подталкивает к вражде без явного призыва к насилию.\n"
    "4) negative — вызывает устойчивую негативную реакцию: резкие оскорбления, "
    "унижение, токсичные высказывания без явной провокации конфликта и без призыва к действиям.\n"
    "Правила:\n"
    "- Верни только валидный JSON без пояснений вне JSON.\n"
    "- Схема: {\"phrases\": [{\"text\": str, \"class\": str, \"confidence\": int, \"reason\": str}]}.\n"
    "- text — дословная цитата из входного текста (не перефразируй).\n"
    "- confidence — целое 0–100 (насколько уверен в классе).\n"
    "- reason — краткое обоснование на русском (1–2 предложения).\n"
    "- Если подходящих фраз нет — {\"phrases\": []}.\n"
    "- Не дублируй одну и ту же фразу. Предпочитай более длинную цитату, "
    "если короткая — её часть.\n"
    "- Не добавляй другие поля и другие классы."
)


def user_prompt_for_chunk(text: str) -> str:
    return (
        f"Текст для анализа:\n{text}\n\n"
        "Ответ (только JSON со схемой {\"phrases\": [...]}):"
    )
